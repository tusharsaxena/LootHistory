-- testkit/client_globals.lua -- the static missing-globals scanner behind tests/_kit/test_client_globals.lua
-- (kit revision 53, WFP-LK-06, LibKa0s#77).
--
-- THE QUESTION. Does this addon call a global function the client does not have? Retail's mock
-- hides the answer: `SetDesaturation(x, true)` is absent from both clients' API, a headless suite
-- never runs the line that reaches it, and a player finds out in the client. The check reads the
-- addon's tracked source, so it needs no run to reach the line.
--
-- THE SETS. `client_globals_live.lua` and `client_globals_forever.lua` (flat: the kit vendors as one folder) are generated by
-- tools/client_globals_data.lua from Ketho/BlizzardInterfaceResources (branches `live` and `forever`,
-- the commit SHAs recorded in each file): the global function names (C API, Lua API, FrameXML) and
-- the `C_Name.Member` pairs. The forever file is stored as its difference from live. A name
-- absent from a client's set is "missing" there.
--
-- WHAT IS A FINDING. A call, in a scanned file, of
--   * a bare name, `Name(`, or
--   * a namespace member, `C_Name.Member(`, where `C_Name` is a Blizzard namespace some client knows,
-- when the name is missing from that client's set, is not declared by the addon, and is not guarded.
--
-- THE HEURISTICS, simple on purpose, and all of them lenient (a false negative beats a red suite that
-- trains people to allowlist):
--   * Comments and strings are blanked first, so a name in either is no call and no guard.
--   * DECLARED: a LOCAL (`local x`, `local function f`, a parameter, a `for` variable) is the
--     addon's own in the file that declares it and nowhere else, so `local X = X` in one file never
--     masks an unguarded call in another. A GLOBAL (`function f(`, `f = ...` at statement start,
--     `_G.f = ...`) is the addon's own in every file. A table field `Name = x,` inside `{}` declares
--     nothing.
--   * GUARDED: a name the same FILE mentions anywhere other than as a call is guarded, whatever the
--     shape: `if X then`, `X and X(`, `local f = X`, `type(X)`, `pcall(X, ...)`. For `C_Name.Member`
--     a bare reference to `C_Name.Member` or to `C_Name` guards it.
--   * Method calls (`obj:Name(`) and field calls (`obj.Name(`) are never findings; only globals are.
--
-- KNOWN FALSE NEGATIVES (lenient by design; each is a call this gate passes):
--   * A guard is file-wide: a call in the else-branch of a test on a different name, or in a
--     function the guard does not cover, passes while the file mentions the name anywhere else.
--   * `_G.Name(`, `_G["Name"](` and `getglobal("Name")` are not read; dynamic names are invisible.
--   * Method and field calls are never checked, so a missing widget method is not found.
--   * A global assignment inside a table constructor's function body is not seen as a declaration,
--     and a name declared by XML or a TOC-loaded file the scan does not list is not known.
--   * Forever findings are best-effort: Ketho's forever set can list names the client lacks (for
--     example GetSpecialization, which the kit's forever profile removes), so a missing name there
--     can be read as present.
--
-- THE ALLOWLIST. The kit ships a path-scoped one, CG.BUILTIN, for vendored library sites (AceGUI's
-- GetSpellInfo else-branch, LibCustomGlow's AnimateTexCoords); it is never stale-checked.
-- `tests/client_globals_allow.lua` returns `{ { name = "X", reason = "why", path = "core/" }, ... }`;
-- `path` is an optional file prefix. A name there is never a finding in its scope; a row with no
-- reason fails, and so does a row no finding reaches.
--
-- WHICH CLIENTS. `live` always. `forever` only when a root `.toc`'s `## Interface` line carries a
-- 16xxx number: an addon that has not been ported declares no Forever load and owes it nothing.

local CG = {}

local KEYWORDS = {}
for w in ([[and break do else elseif end false for function goto if in local nil not or repeat
  return then true until while]]):gmatch("%a+") do KEYWORDS[w] = true end

--- The directory this chunk lives in, with the vendored layout as the fallback.
local function ownDir()
  local info = debug and debug.getinfo and debug.getinfo(2, "S")
  local dir = info and tostring(info.source or ""):match("^@(.*[/\\])")
  return dir or "tests/_kit/"
end
local OWN = ownDir()

--- `src` with every comment and string body blanked to spaces, newlines kept, so line numbers hold.
function CG.strip(src)
  local out, i, n = {}, 1, #src
  local function blank(s) return (s:gsub("[^\n]", " ")) end
  while i <= n do
    local c = src:sub(i, i)
    if c == "-" and src:sub(i + 1, i + 1) == "-" then
      local eq = src:match("^%-%-%[(=*)%[", i)
      local stop
      if eq then
        local _, e = src:find("]" .. eq .. "]", i, true)
        stop = e or n
      else
        stop = (src:find("\n", i, true) or n + 1) - 1
      end
      out[#out + 1] = blank(src:sub(i, stop)); i = stop + 1
    elseif c == '"' or c == "'" then
      local j = i + 1
      while j <= n do
        local d = src:sub(j, j)
        if d == "\\" then j = j + 2
        elseif d == c or d == "\n" then break
        else j = j + 1 end
      end
      out[#out + 1] = c .. blank(src:sub(i + 1, j - 1)) .. (src:sub(j, j) == c and c or "")
      i = j + 1
    elseif c == "[" and src:match("^%[=*%[", i) then
      local eq = src:match("^%[(=*)%[", i)
      local _, e = src:find("]" .. eq .. "]", i, true)
      e = e or n
      out[#out + 1] = blank(src:sub(i, e)); i = e + 1
    else
      local j = src:find("[%-\"'%[]", i + 1) or n + 1
      out[#out + 1] = src:sub(i, j - 1); i = j
    end
  end
  return table.concat(out)
end

--- Add the identifiers of a comma list that starts at `pos` of `code` to `into`.
local function nameList(code, pos, into)
  while true do
    local name, nxt = code:match("^%s*([%a_][%w_]*)%s*()", pos)
    if not name or KEYWORDS[name] then return end
    into[name] = true
    pos = nxt
    local attr = code:match("^<%w+>%s*()", pos)
    if attr then pos = attr end
    local comma = code:match("^,()", pos)
    if not comma then return end
    pos = comma
  end
end

--- Add the names `code` (already stripped) declares: `locals` takes what only this file can see
--- (`local x`, `local function f`, parameters, `for` variables), `globals` what every file can see
--- (`function f(`, `f = ...` at statement start outside a table constructor, `_G.f = ...`). A table
--- field written `Name = x,` inside `{}` is neither.
function CG.declare(code, locals, globals)
  for pos, name, params in code:gmatch("()function%s+([%w_%.:]+)%s*%(([^)]*)%)") do
    if not name:find("[%.:]") then
      local into = code:sub(1, pos - 1):find("local%s+$") and locals or globals
      into[name] = true
    end
    for p in params:gmatch("[%a_][%w_]*") do locals[p] = true end
  end
  for params in code:gmatch("function%s*%(([^)]*)%)") do
    for p in params:gmatch("[%a_][%w_]*") do locals[p] = true end
  end
  for pos in code:gmatch("%f[%w_]local%s+()") do nameList(code, pos, locals) end
  for pos in code:gmatch("%f[%w_]for%s+()") do nameList(code, pos, locals) end
  local text, depth, last = "\n" .. code, 0, 1
  for pos, name in text:gmatch("[\n;]%s*()([%a_][%w_]*)%s*=[^=]") do
    local _, opens = text:sub(last, pos - 1):gsub("{", "")
    local _, closes = text:sub(last, pos - 1):gsub("}", "")
    depth, last = depth + opens - closes, pos
    if depth <= 0 and not KEYWORDS[name] then globals[name] = true end
  end
  for name in code:gmatch("_G%.([%a_][%w_]*)%s*=[^=]") do globals[name] = true end
  return locals
end

--- Is `name` mentioned in stripped `code` other than as a call? `prefix` tokens are allowed to
--- continue it (`C_Name` followed by `.` is a use of a member, not a reference to the namespace).
local function referenced(code, name, allowDot)
  local from = 1
  while true do
    local s, e = code:find(name, from, true)
    if not s then return false end
    from = e + 1
    local before, after = code:sub(s - 1, s - 1), code:sub(e + 1, e + 1)
    if not before:find("[%w_%.:]") and not after:find("[%w_]") then
      local nxt = code:match("^%s*(.)", e + 1) or ""
      local prior = code:sub(1, s - 1):match("(%a+)%s*$")
      if nxt ~= "(" and nxt ~= '"' and nxt ~= "'" and nxt ~= "{" and prior ~= "function"
        and (allowDot or (nxt ~= "." and nxt ~= ":")) then
        return true
      end
    end
  end
end

--- The name sets: `CG.sets(dir)` answers `{ live = {name=true}, forever = {...}, roots = {C_X=true} }`.
function CG.sets(dir)
  dir = dir or OWN
  local live = dofile(dir .. "client_globals_live.lua")
  local forever = dofile(dir .. "client_globals_forever.lua")
  local L, F, roots = {}, {}, {}
  for name in live.names:gmatch("%S+") do L[name] = true; F[name] = true end
  for name in forever.removed:gmatch("%S+") do F[name] = nil end
  for name in forever.added:gmatch("%S+") do F[name] = true end
  for _, set in ipairs({ L, F }) do
    for name in pairs(set) do
      local root = name:match("^(C_[%w_]+)%.")
      if root then roots[root] = true end
    end
  end
  return { live = L, forever = F, roots = roots, meta = { live = live, forever = forever } }
end

--- The clients a TOC's text asks for: `{ "live" }`, or `{ "live", "forever" }` when its Interface
--- line carries a 16xxx number.
function CG.clientsFromToc(toc)
  for line in (toc or ""):gmatch("[^\r\n]+") do
    local list = line:match("^##%s*Interface%s*:%s*(.-)%s*$")
    if list and (" " .. list:gsub(",", " ") .. " "):find("%s16%d%d%d%s") then return { "live", "forever" } end
  end
  return { "live" }
end

--- The calls on one stripped line, as `{ name }` (a bare call) or `{ root, member }` (a `C_` member).
local function callsOf(text)
  local out, pos = {}, 1
  while true do
    local s, e, root = text:find("([%a_][%w_]*)", pos)
    if not s then return out end
    pos = e + 1
    if not text:sub(s - 1, s - 1):find("[%w_%.:]") and not text:sub(1, s - 1):find("[%.:]%s*$")
      and not KEYWORDS[root] then
      if text:find("^%s*%(", e + 1) then
        if text:sub(1, s - 1):match("(%a+)%s*$") ~= "function" then out[#out + 1] = { root } end
      elseif root:find("^C_") then
        local member = text:match("^%.([%a_][%w_]*)%s*%(", e + 1)
        if member then out[#out + 1] = { root, member } end
      end
    end
  end
end

--- Every finding in `files` (`{ { path, src }, ... }`), as `{ file, line, name, client }`, for both
--- clients (the caller picks which count). `sets` is CG.sets's answer.
function CG.scan(files, sets)
  local stripped, locals, globals = {}, {}, {}
  for i, f in ipairs(files) do
    stripped[i] = CG.strip(f[2])
    locals[i] = {}
    CG.declare(stripped[i], locals[i], globals)
  end
  local found, seen = {}, {}
  for i, f in ipairs(files) do
    local code, guard, line = stripped[i], {}, 0
    local function guarded(name, root)
      local key = name
      if guard[key] == nil then
        guard[key] = referenced(code, name, false) or (root ~= nil and referenced(code, root, false))
      end
      return guard[key]
    end
    for text in (code .. "\n"):gmatch("([^\n]*)\n") do
      line = line + 1
      for _, call in ipairs(callsOf(text)) do
        local root, member = call[1], call[2]
        local name = member and (root .. "." .. member) or root
        if not locals[i][root] and not globals[root] and not (member and not sets.roots[root]) then
          for _, client in ipairs({ "live", "forever" }) do
            local key = f[1] .. ":" .. line .. ":" .. name .. ":" .. client
            if not sets[client][name] and not seen[key] and not guarded(name, member and root) then
              seen[key] = true
              found[#found + 1] = { file = f[1], line = line, name = name, client = client }
            end
          end
        end
      end
    end
  end
  return found
end

--- The tracked `.lua` of the repo at `root`, `tests/` and any `skip` prefix left out, as `{ { path, src }, ... }`, and the
--- text of every root `.toc`. Raises when it cannot look: no io.popen, no git or an empty list.
function CG.collect(root, skip)
  root = root or "."
  if not io.popen then error("client globals: io.popen is unavailable, so this gate cannot run", 0) end
  local p = io.popen("git -C '" .. root .. "' ls-files '*.lua' '*.toc' 2>/dev/null")
  if not p then error("client globals: io.popen returned no handle", 0) end
  local files, toc = {}, {}
  for path in p:lines() do
    local isToc = path:find("^[^/]+%.toc$")
    local skipped = path:find("^tests/") ~= nil
    for _, prefix in ipairs(skip or {}) do
      if path:sub(1, #prefix) == prefix then skipped = true end
    end
    if isToc or (path:find("%.lua$") and not skipped) then
      local f = io.open(root .. "/" .. path, "rb")
      if not f then error("client globals: cannot read " .. path, 0) end
      local text = f:read("*a"); f:close()
      if isToc then toc[#toc + 1] = text else files[#files + 1] = { path, text } end
    end
  end
  p:close()
  if #files == 0 then error("client globals: git listed no source files, so nothing was scanned", 0) end
  return files, table.concat(toc, "\n")
end

--- The allowlist rows at `path` (`{ { name, reason } }`); empty when the file is absent.
function CG.allowlist(path)
  local chunk = loadfile(path)
  if not chunk then return {} end
  return chunk() or {}
end

--- The allowlist the kit ships: vendored library sites, scoped by path prefix, so an addon's own
--- code stays checked. Never stale-checked: an addon without the library has no hit to excuse.
CG.BUILTIN = {
  { path = "libs/AceGUI-3.0/", name = "GetSpellInfo",
    reason = "AceGUI's EditBox calls it in the else-branch of a C_Spell presence test" },
  { path = "libs/LibCustomGlow-1.0/", name = "AnimateTexCoords",
    reason = "LibCustomGlow's ants animation calls Blizzard's FrameXML helper" },
}

local function rowTakes(row, hit)
  return row.name == hit.name and (row.path == nil or hit.file:sub(1, #row.path) == row.path)
end

--- Sort findings against the kit's built-in rows and the addon's own: answers `bad` (findings in
--- `clients` no row takes), `problems` (a row with no name or no reason) and `stale` (an addon row
--- no finding in EITHER client reaches). An addon row is `{ name, reason }` with an optional `path`
--- prefix; a name-only row excuses that name in addon code too, so scope it where it can be.
function CG.judge(found, allow, clients)
  local want, used, bad, problems, stale = {}, {}, {}, {}, {}
  for _, c in ipairs(clients) do want[c] = true end
  for i, row in ipairs(allow) do
    if type(row.name) ~= "string" or row.name == "" or type(row.reason) ~= "string" or row.reason == ""
      or (row.path ~= nil and type(row.path) ~= "string") then
      problems[#problems + 1] = ("allowlist row %d needs a name and a reason (and a string path, if any)"):format(i)
    end
  end
  for _, hit in ipairs(found) do
    local taken = false
    for _, row in ipairs(CG.BUILTIN) do
      if rowTakes(row, hit) then taken = true end
    end
    for i, row in ipairs(allow) do
      if rowTakes(row, hit) then used[i] = true; taken = true end
    end
    if not taken and want[hit.client] then
      bad[#bad + 1] = ("%s:%d %s %s"):format(hit.file, hit.line, hit.name, hit.client)
    end
  end
  for i, row in ipairs(allow) do
    if not used[i] and type(row.name) == "string" then stale[#stale + 1] = row.name end
  end
  return bad, problems, stale
end

return CG
