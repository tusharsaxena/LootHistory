--- The optional `tests/prose_waivers.lua`, which a consumer writes and this file reads.
---
--- WHY THIS SEAM EXISTS AT ALL, rather than the kit carrying the exceptions. Some British spellings
--- in a Ka0s tree are not the repository's English to correct, and the kit cannot know which:
--- AceTimer's flag field carries the British double-L spelling of *canceled* and a handle records
--- the flag under that name, because that is what `tests/_kit/mock_record.lua`'s live-timer survey
--- reads off it -- correct it and a stand-down suite's timer assertion goes quietly unfalsifiable.
--- Blizzard spells its `LFG_LIST_APPLICATION_STATUS_UPDATED` status the same way, and an addon
--- matches it verbatim off the event. localization-§5 already says to match game data on the token
--- the game uses; this is that rule meeting this gate. A GENERATED DUMP OF THE CLIENT'S OWN STRINGS
--- IS NOT ONE OF THESE and does not belong here: it is `Kit.prose.exempt` in the runner, beside
--- `Kit.layoutCap.exempt` naming the same folder.
---
--- THE SHAPE IS PER FILE AND PER WORD, never per file alone. A whole-file waiver hides every other
--- British spelling in a file the repo edits often, which is how a gate acquires a blind spot the
--- size of a module. Returning:
---
---     return {
---       skipDirs = { "docs/spell-research/" },        -- optional, named not patterned
---       skipFiles = { ["docs/vendor-notes.md"] = true },
---       waived = {
---         ["core/LifecycleSetup.lua"] = { ["cancel" .. "led"] = true },
---       },
---     }
---
--- `skipDirs` AND `skipFiles` EXTEND THE NAMED EXCLUSION LIST ABOVE, and nothing wider. They are
--- for the categories localization-§5 already names but this kit cannot spell for a consumer — a
--- frozen dated store under a name only that repo knows, a document whose subject is this rule --
--- and not a home for generated data: that is the opts-borne carve-out, in the runner.
---
--- AND THEY FACE THE SAME TWO REFUSALS `Kit.prose.exempt` DOES, over the same resolved coverage: an
--- entry a TOC loads is refused, and one `.pkgmeta` does not ignore -- as written, or for a file it
--- covers -- is refused, because whatever a reader means by the entry, a file inside the packaged
--- payload carries its spellings to a player's screen. They appear in the same disclosure too.
--- `waived` is the only list here not policed that way: it names the word, so it cannot hide one it
--- did not name. Its SHAPE is validated all the same, in `validateWaived` below.
---
--- ABSENT IS THE NORMAL CASE and means no waivers. A repo with nothing to waive ships no file.
local function consumerRules()
    local chunk = loadfile("tests/prose_waivers.lua")
    if not chunk then return {} end
    local ok, rules = pcall(chunk)
    if not ok or type(rules) ~= "table" then
        fail("prose gate: tests/prose_waivers.lua exists but did not return a table (" ..
            tostring(rules) .. "). A waiver file that cannot be read must not be treated as "
            .. "an empty one, because that silently widens the gate", 2)
    end
    return rules
end

--- `waived`, validated. The third key in the same table, and until now the only one with no
--- validation at all: a `waived` that was not a table died inside the scan with a raw Lua error
--- instead of this gate's own words, and the ARRAY FORMS -- `waived = { "core/Foo.lua" }`, or a
--- file's words written as `{ "cancel" .. "led" }` -- waived NOTHING and said nothing, because the
--- scan looks both up by key. That is the silence just removed from `skipFiles`, one key over.
---
--- IT IS POLICED FOR SHAPE HERE AND BY NOTHING ELSE, deliberately: `waived` stays outside the two
--- refusals because it is per FILE and per WORD, so it cannot hide a spelling it did not name --
--- which is why both refusals point at it as the way out. What it CAN do is waive nothing while
--- looking like a waiver.
local function validateWaived(waived)
    if waived == nil then return {} end
    if type(waived) ~= "table" then
        fail("prose gate: " .. SOURCE_WAIVED .. " maps a tracked path to the words waived in it, "
            .. "per file AND per word; this repository set it to a " .. type(waived), 3)
    end
    for path, words in pairs(waived) do
        if type(path) ~= "string" then
            fail("prose gate: " .. SOURCE_WAIVED .. " is KEYED by the path being waived; this key "
                .. "is a " .. type(path) .. ", so the array form waives nothing rather than "
                .. "saying so", 3)
        elseif type(words) ~= "table" then
            fail("prose gate: " .. SOURCE_WAIVED .. "'s entry for " .. path .. " is the set of "
                .. "words waived in that file, per WORD and never per file alone; this one is a "
                .. type(words) .. ", and a whole-file waiver is what localization-§5 forbids", 3)
        else
            for word in pairs(words) do
                if type(word) ~= "string" then
                    fail("prose gate: " .. SOURCE_WAIVED .. "'s entry for " .. path .. " is keyed "
                        .. "by the British spelling being waived, lowercase, as localization-§5 "
                        .. "publishes it; this key is a " .. type(word) .. ", so that array form "
                        .. "waives nothing either", 3)
                end
            end
        end
    end
    return waived
end

--- True when `path` is authored text this section has an opinion about.
---
--- Extension rather than directory, because the authored set is not one tree: locale values sit in
--- `locales/`, comments in `core/`, prose in `docs/` and the TOC's own notes at the root.
--- `.luacheckrc` is named on its own — it is authored Lua with authored comments wearing a different
--- extension, and an extension rule alone would miss it.
local function isAuthoredText(path)
    return path:find("%.lua$") or path:find("%.md$") or path:find("%.toc$") or path == ".luacheckrc"
end

--- Split a NUL-delimited blob. `git ls-files -z` because a path may contain anything but NUL, and
--- the line-oriented form quotes such a path instead of printing it — a quoted path would not open,
--- and this gate would then report a read failure that is really a parse failure.
local function splitNul(blob)
    local out, start = {}, 1
    while true do
        local i = blob:find("\0", start, true)
        if not i then break end
        if i > start then out[#out + 1] = blob:sub(start, i - 1) end
        start = i + 1
    end
    return out
end

--- The authored paths among `all`, minus the named exclusions and minus the exempt set, in order.
---
--- Pure, and separated from the git call below so the self-tests can drive it over a fixture list.
--- The exempt set drops the file outright rather than filtering its hits: a carved-out dump is
--- generated data the gate has no opinion about, and PrettyChat's is 1.6 MB it would read to say
--- nothing.
---
--- A `SCAN_BACK` file is kept against a kit folder, and against a repository `skipDirs` entry that
--- only restates one (`dirCovers`); a wider `skipDirs` entry, or `skipFiles`, still drops it.
local function hiddenByDir(path, skipDirs)
    for _, dir in ipairs(skipDirs) do
        if dirCovers(dir, path) then return true end
    end
    return false
end

local function filterPaths(all, skipFiles, skipDirs, exempt)
    local paths = {}
    for _, path in ipairs(all) do
        if isAuthoredText(path) and not skipFiles[path] and not exempt[path]
            and not hiddenByDir(path, skipDirs) then
            paths[#paths + 1] = path
        end
    end
    return paths
end

--- Every path `git ls-files` reports, read once and kept for the rest of the run.
---
--- Memoized because four readers want it — the scan, the two refusals and the disclosure, which
--- wants it while the suite is still LOADING to write its own case name. A failed read is never
--- cached, so blindness is reported every time rather than once. It is asked of the WHOLE tracked
--- set, before any filtering: an empty answer AFTER filtering has two causes with opposite
--- meanings — git said nothing, or a runner exempted everything — so each is reported as itself,
--- here and at the end of `scannedPaths`.
local trackedCache
local function trackedPaths()
    if trackedCache then return trackedCache end
    if not io.popen then
        fail("prose gate: io.popen is unavailable, so the tracked set cannot be read and this gate "
            .. "must not be reported as passing", 3)
    end
    local pipe = io.popen("git ls-files -z")
    if not pipe then
        fail("prose gate: io.popen returned no handle for `git ls-files`, so this gate cannot run "
            .. "and must not be reported as passing", 3)
    end
    local blob = pipe:read("*a") or ""
    pipe:close()

    local tracked = splitNul(blob)
    if #tracked == 0 then
        fail("prose gate: `git ls-files` reported no tracked files at all, which cannot be true -- "
            .. "either git is unavailable or this is not a repository; this gate cannot run, and "
            .. "must not be reported as passing", 3)
    end
    trackedCache = tracked
    return tracked
end

--- The body of `path`, or nil when it cannot be opened.
local function readFile(path)
    local fh = io.open(path, "r")
    if not fh then return nil end
    local body = fh:read("*a") or ""
    fh:close()
    return body
end

--- localization-§5's own named exclusions, as the two shapes `filterPaths` takes, and nothing else.
---
--- The baseline the disclosure measures FROM: the same in every repository, and `libs/` is loaded
--- by every TOC on purpose, so they are neither refused nor disclosed. What a repository ADDS is.
local function kitExclusionSets()
    local skipFiles = {}
    for k, v in pairs(SKIPPED_FILES) do skipFiles[k] = v end
    local skipDirs = {}
    for _, d in ipairs(SKIPPED_DIRS) do skipDirs[#skipDirs + 1] = d end
    return skipFiles, skipDirs
end

--- The named exclusions plus the consumer's, as the two shapes `filterPaths` takes.
---
--- Built from `waiverNarrowings`, the same reader the two refusals and the disclosure use. ONE
--- READER IS THE POINT: a scan that read `skipFiles` one way while the refusals read it another is
--- a narrowing policed in a shape nobody wrote. It also fixed a silence -- the array form
--- `skipFiles = { "docs/notes.md" }` was copied across key and all, leaving a numeric key no path
--- lookup could hit, so a consumer who wrote it excluded nothing and was told nothing.
local function exclusionSets(rules)
    local skipFiles, skipDirs = kitExclusionSets()
    for _, n in ipairs(waiverNarrowings(rules)) do
        if n.source == SOURCE_SKIPFILES then
            skipFiles[n.entry] = true
        else
            skipDirs[#skipDirs + 1] = n.entry
        end
    end
    return skipFiles, skipDirs
end

--- Every path every tracked `.toc` loads, and how many TOCs were read.
---
--- Zero TOCs is not a failure and not a silence either: the caller SKIPS with the reason, because
--- a repository that packages no addon has no TOC for LOADED BY NOTHING to be read off. A TOC git
--- tracks and this process cannot open IS a failure -- the gate going blind on the condition.
local function tocLoadedPaths()
    local loaded, count = {}, 0
    for _, path in ipairs(trackedPaths()) do
        if path:find("%.toc$") then
            count = count + 1
            local body = readFile(path)
            if body == nil then
                fail("prose gate: git tracks " .. path .. " but it cannot be opened, and it is "
                    .. "where the carve-out's LOADED BY NOTHING condition is read; this gate "
                    .. "cannot look and must not be reported as passing", 3)
            end
            for _, hit in ipairs(tocLoads(path, body)) do loaded[#loaded + 1] = hit end
        end
    end
    return loaded, count
end

--- Every authored path git tracks, minus the named exclusions and the carve-out, in git's order.
local function scannedPaths(rules, exemptEntries)
    local tracked = trackedPaths()
    local skipFiles, skipDirs = exclusionSets(rules)

    local paths = filterPaths(tracked, skipFiles, skipDirs, resolveExempt(exemptEntries, tracked))
    if #paths == 0 then
        fail("prose gate: git tracks " .. #tracked .. " file(s) and the exclusions and the "
            .. "carve-out between them removed every authored one, so this gate would read "
            .. "nothing and report green. Narrow `Kit.prose.exempt` in tests/run.lua, or the "
            .. "skipDirs or skipFiles in tests/prose_waivers.lua, until it reads the repository "
            .. "again -- the disclosure case names which of the three every path came from", 2)
    end
    return paths
end

--- The British substrings present in one line, after `ALLOWED` has been taken out as whole words.
---
--- Whole words, and before the scan, exactly as localization-§5 requires: delimit on non-letters,
--- drop a token that IS an allowance, run the substrings over what is left. Matching `ALLOWED` as a
--- substring would swallow *analysed* inside the allowance for *analyses*.
local ALLOWED_SET = {}
for _, word in ipairs(ALLOWED) do ALLOWED_SET[word] = true end

local function britishIn(line)
    local lowered = line:lower()
    local kept = lowered:gsub("%a+", function(token)
        if ALLOWED_SET[token] then return "" end
        return token
    end)

    local found
    for _, entry in ipairs(BRITISH) do
        if kept:find(entry, 1, true) then
            found = found or {}
            found[#found + 1] = entry
        end
    end
    return found
end

--- Every `path:line - words` hit over `paths`, reading each one through `read(path)`.
---
--- The reader is injected so the self-tests drive THIS function — the one the gate runs —
--- over fixture bodies held in memory, rather than a second copy of the walk that could agree with
--- itself while the real one drifted.
local function collect(paths, read, waived)
    local hits = {}
    for _, path in ipairs(paths) do
        local body = read(path)
        local pass = waived[path]
        local n = 0
        for line in (body:gsub("\r\n", "\n") .. "\n"):gmatch("([^\n]*)\n") do
            n = n + 1
            local found = britishIn(line)
            -- Per WORD, so every other British spelling in a waived file still reddens.
            if found and pass then
                local kept = {}
                for _, entry in ipairs(found) do
                    if not pass[entry] then kept[#kept + 1] = entry end
                end
                found = #kept > 0 and kept or nil
            end
            if found then
                hits[#hits + 1] = string.format("%s:%d - %s", path, n, table.concat(found, ", "))
            end
        end
    end
    return hits
end

