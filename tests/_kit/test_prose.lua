-- testkit/test_prose.lua — the US-English prose gate (localization-§5), over every file git tracks.
--
-- WHAT IT PROVES. That no authored file this repository tracks carries a British spelling from
-- localization-§5's published `BRITISH` list, once the `ALLOWED` US words that contain one of those
-- substrings have been taken out as whole words. Source, locale files, the TOC, `README.md` and
-- every document under `docs/` — the whole authored set, read from git.
--
-- IT SHIPS IN THE KIT, so a consumer inherits it instead of writing its own. Seven repositories had
-- written this gate by hand before it was, under three different file names, and four more had
-- none: a rule enforced by eleven hand-written copies is eleven chances to carry a subset. A
-- REPOSITORY WITH ITS OWN COPY WIRES ONE OR THE OTHER, NEVER BOTH.
--
-- It takes the kit as its chunk argument rather than reading the exposed table, for the reason
-- `test_eol.lua` does: that table's global name belongs to the consumer (`LK_TEST`, `AT_TEST`,
-- …) and a vendored suite cannot know which one it is standing in. Wire it as
-- `{ name = "test_prose", dir = "tests/_kit/" }` in the runner's suite list; the suite inventory
-- goes red until you do, so it cannot arrive with a re-vendor and then quietly run nothing.
--
-- BOTH LISTS ARE COPIED WHOLE, AND NOTHING IS ADDED. localization-§5 is explicit that a gate MUST
-- carry every `BRITISH` and `ALLOWED` entry and MUST NOT carry one the section does not publish: a
-- private list is a coverage claim no reader outside the repo can check. A British form the
-- published list misses is amended in the standard first and arrives here on the next sync.
--
-- THE GENERATED-DATA CARVE-OUT, AND WHY IT ARRIVES THROUGH THE OPTS TABLE. `layout-§1` settled this
-- exact question one revision earlier for the 1500-line cap, and the reasoning transfers whole. A
-- generated dump of the client's own strings is not this repository's English: it is Blizzard's,
-- regenerated by a script, and localization-§5 names it as the third shape a spelling may
-- legitimately carry here. It stands on three conditions, all ABOUT THE REPOSITORY —
--
--   * GENERATED rather than authored: a script writes it and a person does not edit it;
--   * LOADED BY NOTHING: no TOC line, no `dofile`, no runtime reader;
--   * EXCLUDED FROM WHAT A PLAYER DOWNLOADS: `.pkgmeta` keeps it out of the packaged zip.
--
-- — and no path betrays any of the three, so the exempt set ARRIVES THROUGH THE OPTS TABLE the way
-- `Kit.layoutCap.exempt` does, and nothing about a particular repository is compiled in here: a
-- reader who knows one gate knows both.
--
-- TWO OF THE THREE ARE GATED, AND THE FIRST DRAFT GATED NONE OF THEM. A path betrays nothing, but
-- the repository ROOT this gate runs in answers two of them out loud, and reading them is the
-- difference between a carve-out and the whole-file waiver localization-§5 forbids. Measured:
--
--   Kit.prose = { exempt = { "core/WhatGroup.lua", "docs/data-flow.md", "tests/" } }
--
-- WhatGroup's prose gate went GREEN, and `core\WhatGroup.lua` is line 48 of its TOC — five hits
-- suppressed, two of them inside the packaged payload, and the run printed not one word about it.
-- A carve-out that can swallow a shipped file is the escape the rule exists to close. So:
--
--   * A PATH THE TOC LOADS IS REFUSED. Every tracked `.toc` is parsed, its lines resolved against
--     its own folder and its backslashes read as the separators they are, and a declared narrowing
--     covering any of them reddens the run. It reads each TOC's OWN lines and nothing further: an
--     `.xml` line pulls in a tree of `.lua` the TOC never names, and a `dofile` inside a loaded
--     file pulls in more, so the rest of LOADED BY NOTHING stays with the auditor.
--
--   * A PATH `.pkgmeta` DOES NOT IGNORE IS REFUSED. The root `.pkgmeta`'s `ignore:` block is read,
--     and a narrowing no ignore entry covers reddens the run: if the packager puts it in the zip a
--     player downloads its spellings, which is the one thing this rule exists to prevent.
--
--   * WHERE THERE IS NO `.toc`, THE FIRST CHECK DEGRADES RATHER THAN DISAPPEARING: it SKIPS with
--     the reason printed rather than passing quietly, because a library or documentation repo has
--     no TOC for LOADED BY NOTHING to be read off, and a gate that goes green when it cannot look
--     is the failure this file is built against. Same for `.pkgmeta` where nothing is packaged;
--     but a `.toc` with NO `.pkgmeta` is refused, because the packager then ships the tree whole.
--
-- AND BOTH REFUSALS REACH BOTH CHANNELS, WHICH THE FIRST TWO DRAFTS DID NOT. There are two ways a
-- repository narrows this gate, and gating one of them is gating neither. `Kit.prose.exempt` in the
-- runner is the carve-out above; `skipDirs` and `skipFiles` in `tests/prose_waivers.lua` are the
-- named-exclusion list further down this file. They merge into the SAME exclusion sets and take
-- files out of the SAME scan, and until this revision they were checked against nothing at all --
-- while the refusal above pointed a consumer it had just refused straight at them. So every entry
-- in all three lists is a DECLARED NARROWING and both refusals run over the lot: what differs is
-- only what an entry MEANS to a reader, and no meaning survives the file being one that ships.
--
-- EACH CHANNEL IS REFUSED ON ITS OWN MATCHING RULE, never a shared one, AND BOTH REFUSALS READ ONE
-- RESOLVED COVERAGE SET. A `Kit.prose.exempt` entry covers a path or a folder, a `skipDirs` entry
-- is the plain prefix the scan compares, a `skipFiles` entry is one exact path -- matched more
-- loosely, a refusal would reject a narrowing that suppresses nothing; more tightly, it would wave
-- one through on the very file it does take out of the scan. Each entry is resolved through its OWN
-- rule ONCE and everything reads that one resolution, because resolving it apiece is how the two
-- refusals CAME TO DISAGREE ABOUT WHAT THEY REFUSED: packaging asked `.pkgmeta` about the entry AS
-- WRITTEN while the TOC asked about the paths it suppresses, and for an unanchored `skipDirs`
-- prefix checked against an `entry .. "/"` anchor those are different questions. Under a `.pkgmeta`
-- that ignores the `tools` folder, `skipDirs = { "tools" }` hid the shipped root file
-- `tools-notes.md` beside it with BOTH REFUSALS GREEN. Packaging therefore asks about the entry as
-- written AND about every path it covers: the first arm keeps a stale entry honest, the second
-- closes what it left open. An entry covering nothing is refused for its SPELLING instead, because
-- the packaging line would contradict the same run's disclosure.
--
-- THE KIT'S OWN EXCLUSIONS ARE NEITHER REFUSED NOR DISCLOSED. `libs/`, `tests/_kit/`,
-- `locales/enGB.lua` and the frozen dated bundles are localization-§5's published list, identical in
-- every repository and written down below; `libs/` is loaded by every TOC in the collection on
-- purpose. They are the baseline the disclosure measures FROM, not something this repository chose.
--
-- AND THE NARROWING IS DISCLOSED, IN ONE LINE COVERING BOTH CHANNELS. A passing case NAMES every
-- path this repository narrowed the gate by, says which of the three lists each came from, counts
-- the tracked authored files the lot of them suppressed AND NAMES THOSE FILES, grouped under the
-- entry that suppressed each. The count alone was what let a `.pkgmeta`-blessed entry over a
-- shipped file read as ratified rather than as suspicious: nothing tied the number to a file. The
-- list is BOUNDED and says so, because one entry can suppress hundreds and a truncated list a
-- reader takes for a complete one is worse than a count alone. The first draft printed nothing; the
-- second printed the carve-out alone, which is how the older and wider channel beside it went a
-- whole revision unexamined. That case and the two refusals register only where this repository
-- declared a narrowing of its own: an addon with no carve-out and no waiver file has nothing to
-- disclose, and three standing skips every run would be noise a reader learns to scroll past.
--
-- IT IS MEASURED, NOT HYPOTHETICAL. Without the carve-out this gate fails the one repository that
-- had already done everything the rule asked: PrettyChat tracks 27 generated `GlobalStrings/`
-- files, one of them 23,842 lines, and all 34 British spellings this gate reports there are
-- Blizzard constants or sentences. Its hand-written copy named the folder in its skip list and was
-- green; retiring it for this one, which testing-§9 requires, is what takes it red.
--
-- WHAT IT MUST NOT BECOME. localization-§5 forbids a whole-file waiver as a general escape — it
-- hides every OTHER British spelling in a file the repository edits often — and this carve-out
-- MUST NOT be one by the back door. An authored file somebody would rather not fix belongs in
-- `tests/prose_waivers.lua`'s `waived` table, per file AND per word, with the reason beside it:
-- the ONE narrowing the two refusals do not reach, because a waiver that has to name the word
-- cannot hide a spelling it did not name. Its SHAPE is still checked, in `validateWaived` below.
-- In particular: A GENERATED FILE THAT SHIPS IS NOT EXEMPT.
--
-- AND IT IS STILL NOT THE WAIVER FILE'S `skipDirs`, THOUGH THE TWO ARE NOW POLICED ALIKE. Those
-- answer localization-§5's own named-exclusion list — a frozen dated store this kit cannot know the
-- name of, a document whose subject is this rule — while the exempt set sits in `tests/run.lua`,
-- where an auditor already reads `Kit.layoutCap.exempt` naming the SAME folder for the SAME three
-- reasons. One consequence, stated rather than discovered in a red run: a British locale file
-- cannot be taken out by `skipFiles`, because it is TOC-loaded and shipped, so both refusals
-- reject it. `locales/enGB.lua` is excluded by name in the published list below.
--
-- THE THIRD CONDITION IS THE AUDITOR'S CALL AND NEVER THIS GATE'S, drawn where the cap gate draws
-- its equivalent. GENERATED RATHER THAN AUTHORED is a fact about how a file came to exist, and
-- nothing in the repository root records it, so the gate does not guess. A repository that puts a
-- hand-written file in the exempt set, past a TOC that does not load it and a `.pkgmeta` that
-- ignores it, has fooled the gate and will be caught by a reader — which is why the disclosure
-- exists: it puts that set, and the files it suppressed, in front of that reader every run.
--
-- WIRING, in the consumer's `tests/run.lua`, before `Kit.run`:
--
--   Kit.prose = { exempt = { "GlobalStrings/" } }   -- generated, loaded by nothing, not packaged
--
-- Optional, and absent is the normal case: ten of the eleven addons that vendor this kit have no
-- generated data. An entry is a tracked path, or a folder ending in `/`. The waiver file's
-- `skipDirs` and `skipFiles` are the other two lists a repository can narrow this gate by, and
-- every word above about the refusals and the disclosure applies to them unchanged.
--
-- IT FAILS RATHER THAN PASSES WHEN IT CANNOT LOOK. No `io.popen`, no git, an unreadable tracked file
-- — every one of those is a failure, not a skip. A gate that goes quiet when it is blind reports
-- success, which is worse than not existing. Same bargain `test_eol.lua` strikes.

